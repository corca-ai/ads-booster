async function readContextDocuments(relativePaths) {
  if (!Array.isArray(relativePaths) || relativePaths.length === 0) {
    throw new Error("workspace context document list must be non-empty");
  }
  const documents = [];
  for (const relativePath of relativePaths) {
    const text = await readFile(resolve(contextRoot, relativePath), "utf8");
    if (!text.trim()) throw new Error(`blank workspace context: ${relativePath}`);
    documents.push(`[context 문서: ${relativePath}]\n${text}`);
  }
  return documents.join("\n\n");
}

/**
 * Assets ship with the package and are resolvable by a later selection step, but they are never
 * inlined into a generation prompt. The build only proves they exist and are not blank.
 */
async function assertReadableAssets(relativePaths) {
  if (relativePaths === undefined) return;
  if (!Array.isArray(relativePaths)) throw new Error("workspace context asset list must be an array");
  for (const relativePath of relativePaths) {
    const text = await readFile(resolve(contextRoot, relativePath), "utf8");
    if (!text.trim()) throw new Error(`blank workspace context asset: ${relativePath}`);
  }
}

/**
 * Reference bodies are keyed by their frontmatter `id` so a generation call can inline only the
 * records a persona names. The whole corpus is never inlined — see ORIGIN.md.
 */
async function readReferenceBodies(country, relativePaths) {
  if (relativePaths === undefined) return null;
  if (!Array.isArray(relativePaths) || relativePaths.length === 0) {
    throw new Error(`workspace context reference body list for ${country} must be non-empty`);
  }
  const bodies = {};
  for (const relativePath of relativePaths) {
    const text = await readFile(resolve(contextRoot, relativePath), "utf8");
    if (!text.trim()) throw new Error(`blank workspace context reference: ${relativePath}`);
    const id = text.match(/^id:[ \t]*(\S+)[ \t]*$/m)?.[1];
    if (!id) throw new Error(`workspace context reference is missing an id: ${relativePath}`);
    if (!relativePath.endsWith(`/${id}.md`)) {
      throw new Error(`workspace context reference id ${id} does not match ${relativePath}`);
    }
    if (bodies[id]) throw new Error(`duplicate workspace context reference id: ${id}`);
    bodies[id] = text;
  }
  return bodies;
}

/**
 * Context documents are injected in full on every generation, so a country that grows past the
 * budget must fail the build loudly rather than silently truncate mid-table at runtime.
 */
function assertContextBudget(country, globalContext, countryContext) {
  const bytes = Buffer.byteLength(globalContext, "utf8") + Buffer.byteLength(countryContext, "utf8");
  if (bytes > MAX_CONTEXT_BYTES) {
    throw new Error(
      `workspace context for ${country} is ${bytes} bytes, over the ${MAX_CONTEXT_BYTES} byte budget`,
    );
  }
}

function withoutBlock(source, opening, closing) {
  const start = source.indexOf(opening);
  if (start < 0) throw new Error(`workspace template block not found: ${opening}`);
  const end = source.indexOf(closing, start);
  if (end < 0) throw new Error(`workspace template closing block not found: ${closing}`);
  return source.slice(0, start) + source.slice(end + closing.length);
}
