import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const cloudflareRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(cloudflareRoot, "..");
const webStaticRoot = resolve(repoRoot, "src/trace_capture/web/static");
const contextRoot = resolve(repoRoot, "src/trace_capture/assets/context");
const outputRoot = resolve(cloudflareRoot, "dist");
const contextManifestPath = resolve(contextRoot, "profiles/manifest.json");

await rm(outputRoot, { recursive: true, force: true });
await mkdir(resolve(outputRoot, "static"), { recursive: true });

let markup = await readFile(resolve(webStaticRoot, "workspace.html"), "utf8");
markup = withoutBlock(markup, '<section class="workspace-entry"', "</section>");
markup = withoutBlock(markup, '<dialog class="command-dialog" data-invite-dialog', "</dialog>");
markup = markup
  .replace("data-workspace-live aria-busy=\"false\" hidden", "data-workspace-live aria-busy=\"false\"")
  .replace(
    '<a class="skip-link" href="#entry-title">워크스페이스 입장으로 건너뛰기</a>',
    '<a class="skip-link" href="#workspace-content">워크스페이스로 건너뛰기</a>',
  )
  .replace("Trace 팀의 로컬 게시물 후보 워크스페이스입니다.", "Trace 팀의 Cloudflare 공개 게시물 후보 워크스페이스입니다.")
  .replace("Trace 워크스페이스", "Trace Cloudflare 워크스페이스")
  .replace(
    "배경은 외부 이미지 검색에서 출처를 확인해 가져오고, 잠금화면 부품은 저장된 오프라인 이미지를 사용합니다. 위에 입력한 일정과 기기 시각은 기록에는 남지만, 네이티브 캡처 환경(Appium/시뮬레이터)을 연결하기 전까지는 이미지에 그려지지 않습니다.",
    "Cloudflare가 일정과 기기 시각을 넣은 검수용 잠금화면 미리보기를 만듭니다. 이 이미지는 네이티브 Appium 캡처 결과가 아니라 파이프라인 검수용 미리보기입니다.",
  );
await writeFile(resolve(outputRoot, "index.html"), markup, "utf8");

for (const filename of [
  "design-tokens.css",
  "workspace.css",
  "workspace-navigation.js",
  "workspace-live.js",
]) {
  const contents = await readFile(resolve(webStaticRoot, filename));
  await writeFile(resolve(outputRoot, "static", filename), contents);
}

const contextManifest = JSON.parse(await readFile(contextManifestPath, "utf8"));
if (contextManifest.schema_version !== "trace.workspace-context-manifest.v1") {
  throw new Error("unsupported workspace context manifest");
}
const globalContext = await readContextDocuments(contextManifest.global_documents);
const countryContexts = {};
const contextProfiles = [];
for (const [country, config] of Object.entries(contextManifest.countries ?? {})) {
  if (!/^[A-Z]{2}$/.test(country)) throw new Error(`invalid workspace context country: ${country}`);
  countryContexts[country] = await readContextDocuments(config.documents);
  const profiles = JSON.parse(await readFile(resolve(contextRoot, config.profiles), "utf8"));
  if (!Array.isArray(profiles)) throw new Error(`workspace context profiles for ${country} must be an array`);
  if (profiles.some((profile) => profile.country !== country)) {
    throw new Error(`workspace context profiles for ${country} contain another country`);
  }
  contextProfiles.push(...profiles);
}
if (!Array.isArray(contextProfiles) || contextProfiles.length === 0) {
  throw new Error("workspace context profiles must be a non-empty array");
}
for (const profile of contextProfiles) {
  for (const field of ["profile_id", "country", "name", "persona_id", "audience", "situation", "tone", "guidance"]) {
    if (typeof profile[field] !== "string" || !profile[field].trim()) {
      throw new Error(`workspace context profile ${profile.profile_id || "unknown"} is missing ${field}`);
    }
  }
  if (!Array.isArray(profile.reference_ids)) {
    throw new Error(`workspace context profile ${profile.profile_id} has invalid reference_ids`);
  }
}
await writeFile(
  resolve(cloudflareRoot, "src/generated-workspace-context.js"),
  `// Generated by scripts/build-workspace.mjs. Do not edit.\nexport const WORKSPACE_CONTEXT = ${JSON.stringify({ global: globalContext, countries: countryContexts }, null, 2)};\nexport const WORKSPACE_CONTEXT_PROFILES = ${JSON.stringify(contextProfiles, null, 2)};\n`,
  "utf8",
);

console.log("built Cloudflare workspace assets and context");

async function readContextDocuments(relativePaths) {
  if (!Array.isArray(relativePaths) || relativePaths.length === 0) {
    throw new Error("workspace context document list must be non-empty");
  }
  const documents = [];
  for (const relativePath of relativePaths) {
    const text = await readFile(resolve(contextRoot, relativePath), "utf8");
    if (!text.trim()) throw new Error(`blank workspace context: ${relativePath}`);
    documents.push(`[context 문서: ${relativePath}]\n${text}`);
  }
  return documents.join("\n\n");
}

function withoutBlock(source, opening, closing) {
  const start = source.indexOf(opening);
  if (start < 0) throw new Error(`workspace template block not found: ${opening}`);
  const end = source.indexOf(closing, start);
  if (end < 0) throw new Error(`workspace template closing block not found: ${closing}`);
  return source.slice(0, start) + source.slice(end + closing.length);
}
